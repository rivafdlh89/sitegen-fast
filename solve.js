const ESCAPABLE = new Set(['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']);

/** Whether `c` (a char code) is ASCII whitespace. */
function isWsCode(c) {
  return c === 32 || c === 9 || c === 10 || c === 13 || c === 11 || c === 12;
}

/** Whether `line` is blank (spaces and tabs only). */
function isBlank(line) {
  for (let i = 0; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** A fence's language, or null when `line` does not open one. */
function fenceLang(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return null;
  let j = 3;
  while (j < line.length) {
    const c = line.charCodeAt(j);
    if ((c >= 65 && c <= 90) || (c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 95 || c === 43 || c === 45) j++;
    else break;
  }
  const lang = line.slice(3, j);
  while (j < line.length) {
    const c = line.charCodeAt(j);
    if (c !== 32 && c !== 9) return null;
    j++;
  }
  return lang;
}

/** Whether `line` closes a fence. */
function isFenceClose(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return false;
  for (let j = 3; j < line.length; j++) {
    const c = line.charCodeAt(j);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** A heading line's level and text, or null (a heading's text is never empty). */
function headingOf(line) {
  let h = 0;
  while (h < line.length && line.charCodeAt(h) === 35) h++;
  if (h === 0 || h > 6 || h >= line.length) return null;
  const c = line.charCodeAt(h);
  if (c !== 32 && c !== 9) return null;
  let j = h;
  while (j < line.length && (line.charCodeAt(j) === 32 || line.charCodeAt(j) === 9)) j++;
  let e = line.length;
  while (e > j && (line.charCodeAt(e - 1) === 32 || line.charCodeAt(e - 1) === 9)) e--;
  if (e === j) return null;
  return { depth: h, text: line.slice(j, e) };
}

/** Whether `line` is a thematic break. */
function isHr(line) {
  if (line.charCodeAt(0) !== 45 && line.charCodeAt(0) !== 42) return false;
  const p = line.startsWith('---') ? 3 : line.startsWith('***') ? 3 : 0;
  if (p === 0) return false;
  for (let j = 3; j < line.length; j++) {
    const c = line.charCodeAt(j);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** Whether `line` ends a paragraph: blank, fence, heading or thematic break. */
function endsParagraph(line) {
  return isBlank(line) || fenceLang(line) !== null || headingOf(line) !== null || isHr(line);
}

/** A line trimmed of spaces and tabs at both ends. */
function trimLine(line) {
  let a = 0;
  let b = line.length;
  while (a < b && (line.charCodeAt(a) === 32 || line.charCodeAt(a) === 9)) a++;
  while (b > a && (line.charCodeAt(b - 1) === 32 || line.charCodeAt(b - 1) === 9)) b--;
  return a === 0 && b === line.length ? line : line.slice(a, b);
}

/** A list marker: { ordered, start, text }, or null. */
function listMarker(line) {
  const c0 = line.charCodeAt(0);
  if (c0 === 45 || c0 === 42) {
    if (line.charCodeAt(1) === 32) return { ordered: false, start: 1, text: line.slice(2) };
    return null;
  }
  if (c0 >= 48 && c0 <= 57) {
    let j = 0;
    while (j < line.length && line.charCodeAt(j) >= 48 && line.charCodeAt(j) <= 57) j++;
    if (j === 0 || j > 9) return null;
    if (line.charCodeAt(j) !== 46 || line.charCodeAt(j + 1) !== 32) return null;
    return { ordered: true, start: Number(line.slice(0, j)), text: line.slice(j + 2) };
  }
  return null;
}

/** Whether `line` continues a list item: two or more spaces, then a non-space. */
function isContinued(line) {
  let j = 0;
  while (j < line.length && line.charCodeAt(j) === 32) j++;
  if (j < 2 || j >= line.length) return false;
  const c = line.charCodeAt(j);
  if (isWsCode(c)) return false;
  if (c > 127) return !/\s/.test(line[j]);
  return true;
}

/** The first index from `from` where `s` holds `what` outside a backslash escape, or -1. */
function findUnescaped(s, what, from, end) {
  const wlen = what.length;
  for (let j = from; j <= end - wlen; j++) {
    if (s[j] === '\\' && j + 1 < end && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (s.startsWith(what, j)) return j;
  }
  return -1;
}

/** The first single * from `from` (one whose run is not **), outside an escape, or -1. */
function findSingleStar(s, from, end) {
  for (let j = from; j < end; j++) {
    const c = s[j];
    if (c === '\\' && j + 1 < end && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (c !== '*') continue;
    if (j + 1 < end && s[j + 1] === '*') {
      j++;
      continue;
    }
    return j;
  }
  return -1;
}

/** Whether `s` holds any whitespace. */
function hasWS(s) {
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    if (isWsCode(c)) return true;
    if (c > 127 && /\s/.test(s[i])) return true;
  }
  return false;
}

/**
 * `s[start..end)` rendered inline into `out`; `env.link(target)` is a link's href.
 * Plain runs are escaped in bulk; constructs are found with indexOf scans instead of
 * a per-character loop. A construct that does not close stays in the plain run.
 */
function inlineRange(s, start, end, env, out) {
  let i = start;
  let run = start;
  while (i < end) {
    let j = end;
    let k = s.indexOf('\\', i);
    if (k !== -1 && k < j) j = k;
    k = s.indexOf('`', i);
    if (k !== -1 && k < j) j = k;
    k = s.indexOf('*', i);
    if (k !== -1 && k < j) j = k;
    k = s.indexOf('[', i);
    if (k !== -1 && k < j) j = k;
    if (j >= end) break;
    const c = s[j];
    if (c === '\\') {
      if (j + 1 < end && ESCAPABLE.has(s[j + 1])) {
        if (j > run) pushEscaped(s, run, j, out);
        const n = s[j + 1];
        out.push(n === '>' ? '&gt;' : n);
        i = j + 2;
        run = i;
      } else i = j + 1;
      continue;
    }
    if (c === '`') {
      const m = s.indexOf('`', j + 1);
      if (m !== -1 && m < end && m > j + 1) {
        if (j > run) pushEscaped(s, run, j, out);
        out.push('<code>');
        pushEscaped(s, j + 1, m, out);
        out.push('</code>');
        i = m + 1;
        run = i;
      } else i = j + 1;
      continue;
    }
    if (c === '*') {
      if (j + 1 < end && s[j + 1] === '*') {
        const m = findUnescaped(s, '**', j + 2, end);
        if (m > j + 2) {
          if (j > run) pushEscaped(s, run, j, out);
          out.push('<strong>');
          inlineRange(s, j + 2, m, env, out);
          out.push('</strong>');
          i = m + 2;
          run = i;
        } else i = j + 2;
        continue;
      }
      const m = findSingleStar(s, j + 1, end);
      if (m > j + 1) {
        if (j > run) pushEscaped(s, run, j, out);
        out.push('<em>');
        inlineRange(s, j + 1, m, env, out);
        out.push('</em>');
        i = m + 1;
        run = i;
      } else i = j + 1;
      continue;
    }
    const kk = findUnescaped(s, ']', j + 1, end);
    let m = -1;
    if (kk !== -1 && kk + 1 < end && s[kk + 1] === '(') {
      m = s.indexOf(')', kk + 2);
      if (m === -1 || m >= end) m = -1;
    }
    if (m !== -1) {
      const target = s.slice(kk + 2, m);
      if (target !== '' && !hasWS(target)) {
        if (j > run) pushEscaped(s, run, j, out);
        out.push('<a href="', escapeHtml(env.link(target)), '">');
        inlineRange(s, j + 1, kk, env, out);
        out.push('</a>');
        i = m + 1;
        run = i;
        continue;
      }
    }
    i = j + 1;
  }
  if (end > run) pushEscaped(s, run, end, out);
}

/** `s` rendered inline as one string. */
function inline(s, env) {
  const out = [];
  inlineRange(s, 0, s.length, env, out);
  return out.join('');
}

/**
 * `src` rendered: its HTML (each block on its own lines, a "\n" after the last), its table
 * of contents and its excerpt (the first paragraph's inline HTML, or "").
 */
export function renderMarkdown(src, env) {
  const lines = src.split('\n');
  const n = lines.length;
  const out = [];
  const toc = [];
  const ids = new Set();
  let excerpt = null;
  let i = 0;
  while (i < n) {
    const line = lines[i];
    if (isBlank(line)) {
      i++;
      continue;
    }
    const lang = fenceLang(line);
    if (lang !== null) {
      i++;
      out.push('<pre><code' + (lang === '' ? '' : ` class="language-${escapeHtml(lang)}"`) + '>');
      while (i < n && !isFenceClose(lines[i])) {
        pushEscaped(lines[i], 0, lines[i].length, out);
        out.push('\n');
        i++;
      }
      i++;
      out.push('</code></pre>\n');
      continue;
    }
    const heading = headingOf(line);
    if (heading !== null) {
      const id = uniqueSlug(slugify(heading.text), ids);
      const html = inline(heading.text, env);
      out.push(`<h${heading.depth} id="${id}">${html}</h${heading.depth}>\n`);
      if (heading.depth === 2 || heading.depth === 3) toc.push({ level: heading.depth, id, html });
      i++;
      continue;
    }
    if (isHr(line)) {
      out.push('<hr>\n');
      i++;
      continue;
    }
    if (line.charCodeAt(0) === 62) {
      const q = [];
      while (i < n && lines[i].charCodeAt(0) === 62) {
        let l = lines[i].slice(1);
        if (l.charCodeAt(0) === 32) l = l.slice(1);
        l = trimLine(l);
        if (l !== '') q.push(l);
        i++;
      }
      if (q.length === 0) out.push('<blockquote>\n</blockquote>\n');
      else {
        const qt = q.join('\n');
        out.push('<blockquote>\n<p>');
        inlineRange(qt, 0, qt.length, env, out);
        out.push('</p>\n</blockquote>\n');
      }
      continue;
    }
    const first = listMarker(line);
    if (first !== null) {
      const isOrdered = first.ordered;
      const items = [];
      while (i < n) {
        const mm = listMarker(lines[i]);
        if (mm !== null && mm.ordered === isOrdered) {
          items.push([trimLine(mm.text)]);
          i++;
        } else if (isContinued(lines[i])) {
          items[items.length - 1].push(trimLine(lines[i]));
          i++;
        } else break;
      }
      const tag = isOrdered ? 'ol' : 'ul';
      out.push(isOrdered && first.start !== 1 ? `<ol start="${first.start}">\n` : `<${tag}>\n`);
      for (const parts of items) {
        const it = parts.join('\n');
        out.push('<li>');
        inlineRange(it, 0, it.length, env, out);
        out.push('</li>\n');
      }
      out.push(`</${tag}>\n`);
      continue;
    }
    const body = [trimLine(line)];
    i++;
    while (i < n && !endsParagraph(lines[i])) body.push(trimLine(lines[i++]));
    const ptext = body.join('\n');
    if (excerpt === null) {
      const tmp = ['<p>'];
      inlineRange(ptext, 0, ptext.length, env, tmp);
      tmp.push('</p>');
      const html = tmp.join('');
      excerpt = html.slice(3, -4);
      out.push(html, '\n');
    } else {
      out.push('<p>');
      inlineRange(ptext, 0, ptext.length, env, out);
      out.push('</p>\n');
    }
  }
  return { html: out.join(''), toc, excerpt: excerpt ?? '' };
}

